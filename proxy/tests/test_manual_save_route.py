def _png_chunk(kind, payload):
    return (
        len(payload).to_bytes(4, "big") + kind + payload
        + (zlib.crc32(kind + payload) & 0xFFFFFFFF).to_bytes(4, "big")
    )


def _small_png_with_unsafe_dimensions(width=50_000, height=1):
    # Valid PNG framing and a highly-compressible scanline, but unsafe dimensions.
    scanline = b"\x00" + bytes(width * 3)
    image_data = zlib.compress(scanline, level=9)
    ihdr = width.to_bytes(4, "big") + height.to_bytes(4, "big") + b"\x08\x02\x00\x00\x00"
    body = (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"IDAT", image_data)
        + _png_chunk(b"IEND", b"")
    )
    return body


class FakeStore:
    def __init__(self, publish_result="published", outcomes=None):
        self.publish_result = publish_result
        self.outcomes = list(outcomes or [])
        self.begin_target = None
        self.chunks = []
        self.sealed = False
        self.published_basename = None
        self.published_names = []
        self.closed = False

    def begin_owned_stage(self, target_id):
        self.begin_target = target_id
        return "stage-token"

    def append(self, stage, chunk):
        self.chunks.append(bytes(chunk))

    def seal(self, stage):
        self.sealed = True

    def publish_noreplace(self, stage, basename):
        self.published_basename = basename
        self.published_names.append(basename)
        outcome = self.outcomes.pop(0) if self.outcomes else self.publish_result
        if outcome == "published":
            return manual_save_core.StoreResult.PUBLISHED
        return manual_save_core.StoreResult.CONFLICT

    def abort_owned_stage(self, stage):
        return None

    def release_owned_stage(self, stage):
        return None

    def close(self):
        self.closed = True


def _pipeline_deps(tmp_path, *, info=None, url=None, probe=None, decode=None,
                   tag=None, store=None, download=None, make_tempdir=None,
                   lyric=None, cover=None, validate_tagged=None):
    workdir = tmp_path / "work"
    info_payload = _info_payload() if info is None else info
    url_payload = _url_payload() if url is None else url
    fake_store = FakeStore() if store is None else store

    def fake_http(url_text):
        if url_text.endswith("/info"):
            return info_payload
        return url_payload

    lyric_payload = {"ok": True, "data": {"lyric": ""}} if lyric is None else lyric

    def fake_lyric_http(url_text):
        assert url_text.endswith("/lyric")
        return lyric_payload

    def fake_download(media_url, destination):
        assert media_url == SIGNED_URL
        destination.write_bytes(PAYLOAD)
        return {"size": len(PAYLOAD), "md5": PAYLOAD_MD5}

    def fake_probe(_path):
        return {"streams": [{"codec_type": "audio", "codec_name": "flac"}],
                "format": {"format_name": "flac"}}

    def fake_decode(_path):
        return None

    def fake_tag(source, tagged, _metadata):
        tagged.write_bytes(b"TAGGED:" + source.read_bytes())

    def fake_make_tempdir():
        workdir.mkdir(exist_ok=True)
        return workdir

    def fake_open_store(_target_dir, _staging_dir):
        return fake_store

    def fake_validate_tagged(_path, expected_format, metadata, expected_cover):
        streams = [{
            "index": 0,
            "codec_type": "audio",
            "codec_name": "flac" if expected_format == "flac" else "mp3",
        }]
        if expected_cover:
            streams.append({
                "index": 1,
                "codec_type": "video",
                "codec_name": "mjpeg",
                "width": 64,
                "height": 64,
                "disposition": {"attached_pic": 1},
            })
        return {
            "streams": streams,
            "format": {
                "format_name": expected_format,
                "tags": dict(metadata),
            },
        }

    deps = _base_deps(
        http_json=fake_http,
        lyric_json=fake_lyric_http,
        download=download or fake_download,
        verify_cover=lambda _path: None,
        probe=probe or fake_probe,
        decode_check=decode or fake_decode,
        tag=tag or fake_tag,
        open_store=fake_open_store,
        make_tempdir=make_tempdir or fake_make_tempdir,
        cover_fetch=cover,
        validate_tagged=validate_tagged or fake_validate_tagged,
    )
    return deps, fake_store, workdir


