def _png_header(width=64, height=64):
    return (
        b"\x89PNG\r\n\x1a\n"
        + (13).to_bytes(4, "big") + b"IHDR"
        + width.to_bytes(4, "big") + height.to_bytes(4, "big")
        + b"\x08\x02\x00\x00\x00"
    )


def _jpeg_header(width=64, height=64):
    return (
        b"\xff\xd8\xff\xc0\x00\x0b\x08"
        + height.to_bytes(2, "big") + width.to_bytes(2, "big")
        + b"\x01\x01\x11\x00\xff\xd9"
    )


def _webp_header(width=64, height=64):
    payload = b"\x00\x00\x00\x00" + (width - 1).to_bytes(3, "little") + (height - 1).to_bytes(3, "little")
    chunk = b"VP8X" + len(payload).to_bytes(4, "little") + payload
    riff_body = b"WEBP" + chunk
    return b"RIFF" + len(riff_body).to_bytes(4, "little") + riff_body


def _webp_vp8_header(width=64, height=64):
    payload = (
        b"\x00\x00\x00\x9d\x01\x2a"
        + width.to_bytes(2, "little")
        + height.to_bytes(2, "little")
    )
    chunk = b"VP8 " + len(payload).to_bytes(4, "little") + payload
    riff_body = b"WEBP" + chunk
    return b"RIFF" + len(riff_body).to_bytes(4, "little") + riff_body


