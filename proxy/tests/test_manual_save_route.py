def _expected_curl_quote(value):
    escaped = value.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34))
    return chr(34) + escaped + chr(34)


PUBLIC_MEDIA_IPV4 = "93.184.216.34"
